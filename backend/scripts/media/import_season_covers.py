#!/usr/bin/env python3
"""Import season covers (re-runnable).

Looks for <src>/<slug>_s<N>_cover.jpg for every known slug, re-encodes to JPEG q~85
(aspect kept, long side capped at 1920) into media/<slug>/s<N>/cover.jpg, then writes
prisma/season-covers.ts listing ONLY covers that exist in media/, so the seed upserts
seasons.coverPath for those and leaves the drama-level cover.jpg as fallback.
"""
import argparse, glob, os, re, subprocess

BACKEND = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SLUGS = {"mama-in-law-wahala": "dr_mama", "lagos-hustle": "dr_lagos", "village-prince": "dr_prince"}

def dims(p):
    o = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "csv=p=0", p], capture_output=True, text=True).stdout.strip()
    return o.replace(",", "x")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="/workspace/naija-drama/covers")
    a = ap.parse_args()
    for slug in SLUGS:
        for f in sorted(glob.glob(os.path.join(a.src, f"{slug}_s*_cover.jpg"))):
            n = int(re.search(r"_s(\d+)_cover", f).group(1))
            out = os.path.join(BACKEND, "media", slug, f"s{n}", "cover.jpg")
            os.makedirs(os.path.dirname(out), exist_ok=True)
            # q:v 3 ≈ libjpeg quality ~85
            subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", f, "-vf", "scale='if(gt(iw,ih),min(1920,iw),-2)':'if(gt(iw,ih),-2,min(1920,ih))'",
                            "-q:v", "3", out], check=True)
            print(f"imported {f} -> {out} ({dims(out)}, {os.path.getsize(out)//1024}KB)")
    found = []
    for slug, did in SLUGS.items():
        for d in sorted(glob.glob(os.path.join(BACKEND, "media", slug, "s*", "cover.jpg"))):
            n = int(re.search(r"/s(\d+)/cover", d).group(1))
            found.append((did, n, f"{slug}/s{n}/cover.jpg"))
    missing = [s for s in SLUGS if not any(p.startswith(s + "/s1/") for _, _, p in found)]
    lines = ["// GENERATED by scripts/media/import_season_covers.py — do not edit by hand.",
             "// Seasons whose cover exists in backend/media; seed upserts these coverPath values.",
             "export const SEASON_COVERS: ReadonlyArray<{ dramaId: string; seasonNo: number; coverPath: string }> = ["]
    lines += [f"  {{ dramaId: '{d}', seasonNo: {n}, coverPath: '{p}' }}," for d, n, p in found]
    lines += ["];", ""]
    open(os.path.join(BACKEND, "prisma", "season-covers.ts"), "w").write("\n".join(lines))
    print(f"season-covers.ts: {len(found)} entries; missing s1 cover for: {', '.join(missing) or 'none'}")

if __name__ == "__main__":
    main()
